use serde::Deserialize;
use std::env;
use std::error::Error;
use std::fs;
use std::path::PathBuf;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct SchemaRelease {
    crate_version: String,
    schema_revision: u32,
    schema_release: String,
    schema_git_tag: String,
    schema_git_commit: String,
}

fn main() -> Result<(), Box<dyn Error>> {
    let repository = env::args_os()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or(env::current_dir()?);
    let proto_root = repository.join("proto");
    let package_root = proto_root.join("openengine/v1");
    let crate_root = repository.join("packages/rust/openengine");
    let release_manifest = crate_root.join("schema-release.json");
    let output = repository.join("packages/rust/openengine/src/generated");

    fs::create_dir_all(&output)?;

    let release: SchemaRelease = serde_json::from_slice(&fs::read(release_manifest)?)?;
    validate_release(&release)?;
    fs::write(
        output.join("schema.rs"),
        format!(
            "// @generated by openengine-rust-codegen.\n\n\
             /// Monotonically increasing revision of the packaged wire contract.\n\
             pub const SCHEMA_REVISION: u32 = {};\n\n\
             /// Immutable schema release corresponding to these bindings.\n\
             pub const SCHEMA_RELEASE: &str = {:?};\n",
            release.schema_revision, release.schema_release,
        ),
    )?;

    let mut protos = fs::read_dir(&package_root)?
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| {
            path.extension()
                .is_some_and(|extension| extension == "proto")
        })
        .collect::<Vec<_>>();
    protos.sort();

    let protoc = protoc_bin_vendored::protoc_bin_path()?;
    let protobuf_include = protoc_bin_vendored::include_path()?;
    env::set_var("PROTOC", protoc);

    tonic_prost_build::configure()
        .build_client(true)
        .build_server(true)
        .file_descriptor_set_path(output.join("openengine_descriptor.bin"))
        .out_dir(&output)
        .compile_protos(&protos, &[proto_root, protobuf_include])?;

    Ok(())
}

fn validate_release(release: &SchemaRelease) -> Result<(), Box<dyn Error>> {
    if release.schema_revision == 0 {
        return Err("schema_revision must be greater than zero".into());
    }
    if release.crate_version.is_empty() {
        return Err("crate_version must not be empty".into());
    }
    if release.schema_git_tag.is_empty() {
        return Err("schema_git_tag must not be empty".into());
    }
    if !is_lower_hex(&release.schema_release, &[32, 40]) {
        return Err("schema_release must be a 32- or 40-character lowercase hex ID".into());
    }
    if !is_lower_hex(&release.schema_git_commit, &[40]) {
        return Err("schema_git_commit must be a 40-character lowercase Git commit".into());
    }
    Ok(())
}

fn is_lower_hex(value: &str, lengths: &[usize]) -> bool {
    lengths.contains(&value.len())
        && value
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
}
